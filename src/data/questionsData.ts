// Deterministic pseudo-random so options are stable between server and client.
function seeded(n: number) { let s = n * 9301 + 49297; return () => { s = (s * 9301 + 49297) % 233280; return s / 233280; }; }

const worldBySlug = Object.fromEntries(worlds.map((w) => [w.slug, w]));

export const questionsData: QuestionItem[] = raw.map(([slug, question, answer, page, evidence], idx) => {
  const w = worldBySlug[slug]!;
  const category = w.category as "عقيدة" | "آداب";
  const pool = raw.filter((r, j) => j !== idx && (worldBySlug[r[0]]!.category === category) && r[2] !== answer).map((r) => r[2]);
  const rnd = seeded(idx + 1);
  const wrong = new Set<string>();
  while (wrong.size < 3 && wrong.size < pool.length) wrong.add(pool[Math.floor(rnd() * pool.length)]!);
  return {
    id: idx + 1, world: w.name, category, question,
    options: [answer, ...wrong], correctAnswer: answer,
    explanation: evidence ? `${answer}. ${evidence}` : answer,
    sourcePage: page,
  };
});

export function questionsForWorld(slug: string): QuestionItem[] {
  const w = worlds.find((x) => x.slug === slug);
  if (!w) return [];
  if (slug === "heroes") return shuffle(questionsData); // the full exam: every question
  return questionsData.filter((q) => q.world === w.name);
}

export function shuffle<T>(arr: T[]): T[] {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(Math.random() * (i + 1)); [a[i], a[j]] = [a[j]!, a[i]!]; }
  return a;
}
